export const FIXED_DT = 1 / 60;
export const FIXED_DT_MS = 1000 * FIXED_DT;

export function msToTicks(durationMs: number): number {
  if (!Number.isFinite(durationMs) || durationMs < 0) {
    throw new RangeError('Tick durations must be finite and non-negative.');
  }

  return Math.round(durationMs / FIXED_DT_MS);
}

